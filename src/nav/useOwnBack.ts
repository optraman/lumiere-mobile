import { useCallback } from 'react';
import { router, useNavigation } from 'expo-router';

/*
  «НАЗАД» — СВОЕЙ СТРАНИЦЫ, А НЕ ВЕРХНЕЙ.

  router.back() закрывает ту страницу, что сейчас наверху стопки, — какой бы она ни была. Если по
  какой-то причине поверх осталась другая (например, страница фильма, открытая из кинофеста, ещё
  не успела сняться), закрытие кинофеста снимало ЕЁ: на миг проступала «страница какого-то фильма»,
  а сам кинофест оставался лежать невидимым поверх всего — и приложение переставало отвечать.

  Здесь назад идёт сама страница (navigation.goBack из её собственного навигатора): снимается
  именно она и всё, что над ней. Ничего лишнего наверху остаться не может.
*/
export function useOwnBack(): () => void {
  const nav = useNavigation();
  return useCallback(() => {
    try {
      if (nav.canGoBack()) nav.goBack();
      else router.back();
    } catch {
      router.back();
    }
  }, [nav]);
}
