import { router, type Href } from 'expo-router';

/*
  ЗАЩИТА ОТ ПЕРЕХОДОВ ВО ВРЕМЯ ЗАКРЫТИЯ СТРАНИЦЫ — главная причина «после выхода из кинофеста /
  настроения приложение не отвечает».

  Как это происходило. Страницу закрывают жестом от левого края — палец при этом едет по строке
  списка (фильм в кинофесте, фильм в настроении). Жест закрытия забирает палец, но строка всё
  равно получала «нажатие» в момент отпускания — и открывала страницу фильма ровно тогда, когда
  кинофест закрывался. Два модальных окна одновременно — одно появляется, другое уходит — iOS
  такого не переносит: страница фильма на миг мелькала («появляется страница какого-то фильма»),
  а невидимое окно оставалось поверх всего и забирало все касания и прокрутку.

  Теперь: пока страницу тянут жестом, пока она закрывается и ещё полсекунды после — любые
  переходы на новые страницы игнорируются. Все переходы со строк и плиток идут через go()/
  allowed() (openTitle, кинофесты, настроения, списки с главной).
*/
let lockedUntil = 0;
let pushedAt = 0;

/** Сколько прошло с последнего перехода на новую страницу. */
export function msSincePush(): number {
  return Date.now() - pushedAt;
}

/** Отметить переход (для переходов, которые идут не через go()). */
export function markPush(): void {
  pushedAt = Date.now();
}

/** Страницу тянут или закрывают — переходы запрещены ещё ms миллисекунд. */
export function holdNavigation(ms = 500): void {
  lockedUntil = Math.max(lockedUntil, Date.now() + ms);
}

/**
 * Страница закрылась — запрет снимается почти сразу (через 120 мс, чтобы отпускание пальца,
 * закрывшего страницу, не нажало ничего под ним). Раньше запрет держался свои 700 мс и после
 * закрытия, и касания на Главной в эти доли секунды пропадали — «приходится нажимать несколько раз».
 */
export function releaseNavigation(afterMs = 120): void {
  lockedUntil = Date.now() + afterMs;
}

export function navigationAllowed(): boolean {
  return Date.now() >= lockedUntil;
}

/** router.push, который не срабатывает во время закрытия страницы. */
export function go(href: Href): void {
  if (!navigationAllowed()) return;
  holdNavigation(250); // двойное касание не открывает страницу дважды
  markPush();
  router.push(href);
}
