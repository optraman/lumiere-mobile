import { useCallback, useEffect, useMemo, useRef, useState } from 'react';
import { holdNavigation, msSincePush, releaseNavigation } from './navGuard';
import { Animated } from 'react-native';
import { Motion } from '../theme/motion';
import { useA11ySettings } from '../theme/a11y';

/**
 * Открытие и закрытие страницы фильма: постер РАЗВОРАЧИВАЕТСЯ, страница проявляется. Назад — то же
 * самое в обратную сторону.
 *
 * Работают ТОЛЬКО прозрачность и равномерный масштаб — единственные два свойства, которые считает
 * нативный драйвер. Всё остальное (размеры рамок, скругления, сила размытия) считается в JS-потоке,
 * а он в этот самый момент занят разбором ответа TMDB: именно это делало прошлые версии тяжёлыми.
 *
 * ОТЗЫВЧИВОСТЬ — это не только длительность. Взято три вещи:
 *   • пружина вместо кривой: она стартует резко и мягко оседает, поэтому палец получает ответ
 *     мгновенно, а глаз — плавную остановку;
 *   • открытие 190 мс по ощущению (пружина не имеет фиксированной длительности, здесь она подобрана
 *     жёсткой), закрытие ещё быстрее — решение уже принято, ждать нечего;
 *   • масштаб от 0.84: на 0.90 рост был почти не виден — страница как будто просто проявлялась.
 *     Шестнадцать процентов уже читаются как разворот, но это всё ещё рост предмета, а не
 *     вылет из точки.
 */
const START_SCALE = 0.88;
/** Открытие и закрытие. Обе величины детерминированные, потому что от них зависит не только
 * ощущение, но и МОМЕНТ, когда экран размонтируется и предыдущий снова начнёт принимать касания. */
const OPEN_MS = 170;
const CLOSE_MS = 80;

/**
 * ПРУЖИНЫ ЗДЕСЬ БОЛЬШЕ НЕТ, и это осознанно.
 *
 * Пружина приятна на глаз, но у неё нет конца: она затухает асимптотически, и «доезд» последних
 * процентов занимает больше времени, чем всё видимое движение. Для открытия это лишняя вязкость,
 * а для закрытия — ещё и задержка, потому что экран размонтируется только по завершении.
 *
 * timing с короткой длительностью и медленным выходом кривой Влада читается так же мягко, но
 * заканчивается ровно тогда, когда сказано.
 */

export function useScreenZoom(onClosed: () => void) {
  const { reduceMotion } = useA11ySettings();
  const t = useRef(new Animated.Value(0)).current;
  const closing = useRef(false);
  /*
    Закрывающаяся страница сразу перестаёт принимать касания: даже если её снятие со стопки
    запоздает, она не перехватит ни одного касания у страницы под ней.
  */
  const [interactive, setInteractive] = useState(true);

  useEffect(() => {
    if (reduceMotion) {
      t.setValue(1);
      return;
    }
    Animated.timing(t, {
      toValue: 1,
      duration: OPEN_MS,
      easing: Motion.curve,
      useNativeDriver: true,
    }).start();
  }, [reduceMotion, t]);

  const close = useCallback(
    (velocity = 0) => {
      if (closing.current) return;
      closing.current = true;
      setInteractive(false);
      holdNavigation(700);
      if (reduceMotion) {
        onClosed();
        return;
      }
      /**
       * ЗАКРЫТИЕ — timing, а не пружина, и это не вкусовщина.
       *
       * Пружина не имеет конца: она затухает асимптотически, и колбэк завершения срабатывает не
       * когда движение стало незаметным, а когда система решит, что оно улеглось. Экран к этому
       * моменту давно выглядит закрытым, но остаётся смонтированным — и главная под ним не
       * принимает касания. Отсюда те самые полсекунды, когда «уже вернулся, но ещё нельзя листать».
       *
       * timing заканчивается ровно тогда, когда сказано.
       */
      /*
        ВО ВРЕМЯ ЗАКРЫТИЯ НЕ ПРОИСХОДИТ БОЛЬШЕ НИЧЕГО, и это главное условие, а не длительность.

        Раньше в эти же миллисекунды страница успевала перерисоваться (снимались списки), снять с
        себя растр и на середине анимации размонтироваться. Всё это — работа рисующего потока, и
        шла она поверх собственной анимации: та не успевала показать последние кадры и застывала
        призраком, который вдобавок ещё держал касания. Отсюда и «залипает на последнем кадре».

        Теперь порядок строгий: сначала движение, и только по его окончании — снятие экрана. Само
        движение короткое (80 мс — пять кадров) и идёт на нативном драйвере, то есть JS в это время
        свободен. Меньше уже нельзя: пропадание без единого кадра движения читается как сбой, а не
        как закрытие.
      */
      /*
        ЗАКРЫТЬСЯ — ВСЕГДА. Раньше экран снимался только при «досмотренной» анимации. Если её
        что-то прерывало (палец ещё вёл жест, перерисовка), колбэк приходил с finished = false —
        и невидимый экран оставался лежать поверх страницы, забирая касания: страница сериала
        после выхода из списка серий «замерзала». Теперь снимаем при любом исходе и, на всякий
        случай, по таймеру.
      */
      let gone = false;
      const done = () => {
        if (gone) return;
        gone = true;
        onClosed();
        releaseNavigation();
      };
      const ms = Math.max(70, CLOSE_MS - velocity * 20);
      /*
        Если только что (меньше полусекунды назад) открывали новую страницу — закрытие ждёт, пока
        она встанет. Закрывать одно модальное окно, пока iOS показывает другое, нельзя: невидимое
        окно оставалось поверх и блокировало приложение.
      */
      const wait = Math.max(0, 480 - msSincePush());
      setTimeout(() => {
        Animated.timing(t, {
          toValue: 0,
          duration: ms,
          easing: Motion.curve,
          useNativeDriver: true,
        }).start(() => done());
        setTimeout(done, ms + 250);
      }, wait);
    },
    [reduceMotion, t, onClosed],
  );

  /** Тянуть анимацию пальцем: 1 — открыто, 0 — закрыто. */
  const setProgress = useCallback(
    (p: number) => {
      holdNavigation(500);
      if (reduceMotion) return;
      t.setValue(Math.min(Math.max(p, 0), 1));
    },
    [t, reduceMotion],
  );

  /** Отпустили, но не закрыли — вернуть на место. */
  const settleOpen = useCallback(() => {
    closing.current = false;
    setInteractive(true);
    // Передумали закрывать — запрет снимается, как только палец точно отпущен.
    releaseNavigation(250);
    Animated.timing(t, {
      toValue: 1,
      duration: Motion.FOCUS,
      easing: Motion.curve,
      useNativeDriver: true,
    }).start();
  }, [t]);

  // Стили и сам объект — ОДНИ на всё время жизни страницы (useMemo): раньше каждая перерисовка
  // заново строила интерполяцию масштаба и новые объекты стилей, Animated пересобирал узлы
  // нативного графа, а зависящие от zoom колбэки страниц (startClose и т.п.) менялись каждый раз.
  const pageStyle = useMemo(
    () => ({
      opacity: t,
      transform: [{ scale: t.interpolate({ inputRange: [0, 1], outputRange: [START_SCALE, 1] }) }],
    }),
    [t],
  );
  const backdropStyle = useMemo(() => ({ opacity: t }), [t]);

  return useMemo(
    () => ({ pageStyle, backdropStyle, close, setProgress, settleOpen, interactive }),
    [pageStyle, backdropStyle, close, setProgress, settleOpen, interactive],
  );
}
