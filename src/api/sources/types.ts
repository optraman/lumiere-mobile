/**
 * ОБЩИЙ ЯЗЫК ВСЕХ ИСТОЧНИКОВ.
 *
 * Источников теперь десяток, и каждый отвечает по-своему: один отдаёт весь сериал одной страницей,
 * другой — список озвучек, по которым ссылку на серию надо ещё выпросить, третий — голые mp4 по
 * качествам. Плееру всё это различие не нужно. Ему нужно одно: «вот серия, вот варианты её
 * воспроизведения, вот как получить ссылку». Этот файл и есть тот общий язык, к которому каждый
 * источник приводит свой ответ.
 */

/** Что мы знаем о тайтле, когда идём его искать. */
export type Ids = {
  title: string;
  originalTitle: string | null;
  year: number | null;
  imdb: string | null;
  /** Номер Кинопоиска. ТМДБ его не знает — его добывают отдельно (см. ids.ts). */
  kp: number | null;
  /** Номер ТМДБ — он есть всегда: с него приложение и начинает. Английские источники ищут по нему. */
  tmdb?: number | null;
  kind: 'movie' | 'serial';
  /**
   * Номер Кинопоиска «потом»: он добывается параллельно и может прийти позже старта источника.
   * Источнику, который сначала ищет по IMDb (Collaps), он нужен только если по IMDb не нашлось —
   * тогда он дождётся номера сам (с ограничением по времени), а не сдастся сразу.
   */
  kpLater?: () => Promise<number | null>;
};

export type Caption = { name: string; url: string };

/**
 * ОДИН ВАРИАНТ ВОСПРОИЗВЕДЕНИЯ: озвучка, качество и ссылка.
 *
 * Ссылка бывает готовой (`url`), а бывает, что за ней надо сходить ещё раз (`resolve`): у части
 * источников список серий бесплатный, а каждая конкретная ссылка стоит отдельного запроса. Делать
 * эти запросы заранее для всех трёхсот серий — расточительство, поэтому они откладываются до
 * момента, когда серию действительно включают.
 */
export type Variant = {
  voice: string;
  /** «1080p» — если источник честно его называет; null — плейлист сам подберёт качество. */
  quality: string | null;
  url?: string;
  resolve?: (signal?: AbortSignal) => Promise<string | null>;
  /**
   * Готовые файлы MP4 по качествам — для ЗАГРУЗКИ, если источник их даёт. Один обычный файл
   * надёжнее потока из сотен кусков: его не надо склеивать, и iPhone играет его с диска всегда.
   */
  files?: (signal?: AbortSignal) => Promise<{ url: string; height: number }[]>;
  /** Заголовки, без которых раздача не отдаёт файл. */
  headers: Record<string, string>;
  captions?: Caption[];
  /** Озвучки, лежащие дорожками внутри самого файла (как у Collaps). */
  tracks?: string[];
  /**
   * Дорожки внутри файла человеку не показывать: вариант — это ОДНА озвучка из меню, и плеер
   * сам выбирает в файле нужную (английскую). Так у VixSrc, где рядом с оригиналом лежит итальянская.
   */
  hideTracks?: boolean;
};

export type Episode = { episode: number; title: string | null; variants: Variant[] };
export type Season = { season: number; episodes: Episode[] };

export type Found =
  | { kind: 'movie'; variants: Variant[] }
  | { kind: 'serial'; seasons: Season[] };

/** По чему источник умеет искать. Достаточно ЛЮБОГО из перечисленного. */
export type Key = 'imdb' | 'kp' | 'title' | 'tmdb';

export type Source = {
  id: string;
  /** Как показывать человеку: «Collaps», «HDVB», «VK Видео». */
  name: string;
  movie: boolean;
  serial: boolean;
  needs: Key[];
  /**
   * Обычное качество источника по высоте кадра — когда он отдаёт плейлист без подписи качества.
   * Нужно для выбора лучшего источника: «авто» у одного и «авто» у другого — это разные потолки.
   */
  typical: number;
  open(ids: Ids, signal: AbortSignal): Promise<Found | null>;
};
