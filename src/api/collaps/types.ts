/**
 * ЧТО ОТДАЁТ COLLAPS.
 *
 * Формы списаны с открытого исходника Lampac (Modules/OnlineRUS/Collaps/Model.cs) и сверены с
 * живым ответом — выгрузка лежит в tools/collaps-last.json. Лишних полей здесь нет намеренно:
 * в ответе их полтора десятка (download, sections, poster-заглушка, превью-спрайты), и каждое
 * вытащенное наружу поле — это ещё одно место, где источник может поменяться и сломать экран.
 */

/** Один субтитровый трек: подпись и прямая ссылка на .vtt. */
export type Caption = { name: string; url: string };

/**
 * ОДНА СЕРИЯ.
 *
 * Главное здесь — что ссылка ОДНА. Озвучки лежат дорожками ВНУТРИ этого же master.m3u8
 * (`audio: {"names":[…]}`), а не отдельными файлами, как было у резки. Поэтому смена озвучки
 * здесь ничего не пересобирает и никуда не ходит: это переключение аудиодорожки в плеере.
 */
export type Episode = {
  /** Номер серии строкой — ровно как приходит («1», «12»). */
  episode: string;
  /** «Теория большого взрыва (1 сезон) - 1 серия» — готовая подпись от источника. */
  title: string | null;
  /** Длительность в секундах; нужна, чтобы показать её до начала загрузки. */
  durationSec: number | null;
  hls: string | null;
  dash: string | null;
  captions: Caption[];
  /** Названия озвучек в том же порядке, в каком дорожки идут в плейлисте. */
  voices: string[];
  /**
   * ЛЕНТА КАДРИКОВ ДЛЯ ПЕРЕМОТКИ — адрес с подстановкой `${spriteNum}`.
   *
   * Источник раскладывает маленькие кадры сеткой по нескольким картинкам (как это делает ютуб) и
   * отдаёт шаблон адреса. Чтобы показать кадр под пальцем, надо знать ещё две вещи: сколько кадров
   * в одной картинке и сколько секунд между ними. В ответе этого нет, и угадывать я не буду —
   * сначала надо посмотреть на саму картинку (tools/collaps-probe.js --preview).
   */
  previewTemplate: string | null;
};

export type Season = { season: number; episodes: Episode[] };

export type Movie = {
  hls: string | null;
  dash: string | null;
  captions: Caption[];
  voices: string[];
};

/** Страница плеера бывает ровно двух видов — так же, как у Lampac в Invoke.Embed. */
export type Title =
  | { kind: 'movie'; movie: Movie }
  | { kind: 'serial'; seasons: Season[] };

/** По чему открываем: внешний идентификатор, не их внутренний. Их поиск требует токена, этот путь — нет. */
export type Ref = { imdb: string } | { kp: number } | { orid: number };
