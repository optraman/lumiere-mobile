export const KINOFESTS: Kinofest[] = RAW.map(([id, title, blurb, heroId, heroTitle, heroBackdrop, window, entries]) => ({
  id,
  title,
  blurb,
  heroId,
  heroTitle,
  heroBackdrop,
  window,
  entries: entries.map(([eid, t, year, note]) => ({ id: eid, title: t, year, note, type: TV_IDS.has(eid) ? 'tv' : 'movie' })),
}));

const md = (d: Date) => (d.getMonth() + 1) * 100 + d.getDate();

/** Сколько дней до даты (месяц, день; год — ближайший такой день впереди, если не задан). */
function daysTo(now: Date, month: number, day: number, year?: number): number {
  const start = new Date(now.getFullYear(), now.getMonth(), now.getDate());
  let target = new Date(year ?? now.getFullYear(), month - 1, day);
  if (year == null && target < start) target = new Date(now.getFullYear() + 1, month - 1, day);
  return Math.round((target.getTime() - start.getTime()) / 86_400_000);
}

const daysWord = (n: number) => {
  const a = n % 100;
  const b = n % 10;
  return a >= 11 && a <= 14 ? 'дней' : b === 1 ? 'день' : b >= 2 && b <= 4 ? 'дня' : 'дней';
};

/** Показывать ли кинофест сегодня (окно — как у Влада, L4/d.b и L4/e.b). */
export function isOpen(k: Kinofest, now = new Date()): boolean {
  const v = md(now);
  if (k.window === 'halloween') return v >= 1008 && v <= 1103;
  if (k.window === 'newyear') return v >= 1212 || v <= 107;
  if (k.window === 'doomsday') return daysTo(now, 12, 18, 2026) >= -7;
  return true;
}

/** Подпись-отсчёт: «Хеллоуин через 18 дней», «премьера через 66 дней» (L4/d.a, L4/e.a). */
export function countdown(k: Kinofest, now = new Date()): string | null {
  const say = (label: string, n: number) =>
    n === 1 ? `${label} завтра` : n === 0 ? `${label} сегодня` : n < 0 ? null : `${label} через ${n} ${daysWord(n)}`;
  if (k.window === 'halloween') return say('Хеллоуин', daysTo(now, 10, 31));
  if (k.window === 'newyear') return say('Новый год', daysTo(now, 1, 1));
  if (k.window === 'doomsday') {
    const n = daysTo(now, 12, 18, 2026);
    return n <= 1 ? (n === 1 ? 'премьера завтра' : n === 0 ? 'премьера сегодня' : 'уже в кино') : `премьера через ${n} ${daysWord(n)}`;
  }
  return null;
}

/** Кинофесты на сегодня: сезонные (если их время) — первыми, дальше остальные по каталогу. */
export function kinofestsNow(now = new Date()): Kinofest[] {
  const open = KINOFESTS.filter((k) => isOpen(k, now));
  return [...open.filter((k) => k.window !== 'always'), ...open.filter((k) => k.window === 'always')];
}

export function kinofestById(id: string): Kinofest | undefined {
  return KINOFESTS.find((k) => k.id === id);
}
