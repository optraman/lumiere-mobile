// ТРИ длительности и ОДНА кривая — на всё. До этого в приложении Влада одни и те же движения шли на
// 140, 150, 160, 180, 200, 220, 240, 260, 280 и 300 мс с тремя разными кривыми, выбранными наугад.
// Глаз читает это не как разнообразие, а как интерфейс, собранный из несвязанных кусков. Общая
// кривая и крошечный набор длительностей — это и есть большая часть того, что делает интерфейс
// дорогим на ощупь. Не заводить здесь новых значений «по случаю».
//
// Кривая — медленный выход (0.2, 0, 0, 1): движение стартует сразу и мягко оседает; на входе
// читается как отзывчивость, на выходе — как спокойствие.

import { Easing } from 'react-native';

