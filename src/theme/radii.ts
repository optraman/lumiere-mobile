/**
 * КОНЦЕНТРИЧНОСТЬ — геометрическое правило Liquid Glass.
 *
 * Радиус скругления внутреннего элемента не выбирается на глаз, а ВЫЧИСЛЯЕТСЯ: он равен радиусу
 * внешнего контейнера минус отступ между ними. Тогда вложенные формы читаются как один вложенный
 * контур. Если радиусы подобраны произвольно, на отступе появляется зазор неравной толщины —
 * скругления «спорят» друг с другом, даже когда разница пара пикселей.
 *
 * Отсчёт идёт от КОРПУСА УСТРОЙСТВА: радиус экрана — внешняя константа, от которой пляшет всё
 * остальное.
 */

/**
 * Радиус скругления экрана iPhone в точках.
 *
 * Публичного API, чтобы спросить его у системы, в React Native нет. 55 — значение для нынешних
 * моделей с Dynamic Island; у более старых с «чёлкой» ближе к 47. Ошибка в несколько точек здесь
 * не критична: важна СВЯЗАННОСТЬ радиусов между собой, а не абсолютная точность каждого. Если
 * когда-нибудь появится способ спросить систему — менять только эту строку.
 */
export const SCREEN_RADIUS = 55;

/**
 * Радиус элемента, вложенного в контейнер с радиусом [outer] на отступе [inset].
 *
 * Не даёт уйти ниже нуля: при отступе больше радиуса контейнера концентричным решением становится
 * прямой угол, а не отрицательное скругление.
 */
export function concentric(outer: number, inset: number): number {
  return Math.max(outer - inset, 0);
}

/** Поля карточек героя от края экрана. */
export const HERO_INSET = 16;

/** Карточка героя вложена прямо в экран, поэтому её радиус — радиус экрана минус её отступ. */
export const HERO_RADIUS = concentric(SCREEN_RADIUS, HERO_INSET);

/** Развёрнутая страница занимает экран целиком: её углы совпадают с углами дисплея. */
export const PAGE_RADIUS = SCREEN_RADIUS;
