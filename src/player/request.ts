import type { MediaType } from '../types/media';

/** Один субтитровый трек: подпись и прямая ссылка на VTT. */
export type SubtitleTrack = { label: string; lang: string | null; url: string };

/** Одна серия сериала — для перехода вперёд/назад и выбора внутри плеера. */
export type EpisodeRef = { season: string; episode: string; label: string };

/**
 * ВСЁ, ЧТО ПЛЕЕРУ НУЖНО, ЧТОБЫ НАЧАТЬ.
 *
 * Запрос стал заметно короче, и каждое исчезнувшее поле стоит назвать — иначе через месяц кто-то
 * (я же) решит, что их потеряли по недосмотру.
 *
 * НЕТ СПИСКА КАЧЕСТВ. Источник отдаёт master-плейлист HLS: качества лежат внутри него, и плеер
 * выбирает их сам по ширине канала. Меню качества здесь было бы выбором между «авто» и «хуже,
 * чем авто».
 *
 * НЕТ СПИСКА ОЗВУЧЕК КАК ВАРИАНТОВ ССЫЛКИ. Озвучки — это звуковые дорожки ВНУТРИ того же файла.
 * Сменить озвучку значит переключить дорожку в плеере: ни запроса, ни пересборки ссылки, ни
 * запасного «Оригинала» на случай, если серии в этом дубляже не окажется. Поле `voices` оставлено
 * только ради подписи, пока плеер не прочитал дорожки из самого плейлиста.
 *
 * НЕТ pageUrl, postId И НОМЕРОВ ПЕРЕВОДЧИКОВ. Это был контекст, нужный, чтобы собрать СЛЕДУЮЩИЙ
 * запрос к источнику. Следующего запроса больше нет: весь сериал приезжает одной страницей.
 */
export type PlaybackRequest = {
  url: string;
  title: string;
  /** «Сезон 1 · Серия 5» — под названием; у фильмов пусто. */
  subtitle: string | null;
  isHls: boolean;
  /** Заголовки, без которых раздача не отдаёт файл. */
  headers: Record<string, string>;
  subtitleTracks: SubtitleTrack[];
  /** Названия звуковых дорожек в порядке их следования в плейлисте. */
  voices: string[];
  /** Дорожка, которую включить при старте (голос, выбранный для тайтла раньше), — если есть в файле. */
  preferTrack?: string | null;
  /** Длительность от источника — чтобы показать её, не дожидаясь загрузки. */
  durationSec: number | null;
  /** Ключ журнала просмотра — по нему возобновляется позиция. */
  mediaKey: string;
  mediaId: number;
  mediaType: MediaType;
  posterUrl: string | null;
  backdropUrl: string | null;
  startPositionMs: number;
  // --- контекст сериала: по нему плеер сам находит соседние серии ---
  /** Номер тайтла у источника; по нему берётся уже разобранная страница из памяти. */
  imdb: string | null;
  season: string | null;
  episode: string | null;
  /** Все серии сериала по порядку. */
  episodes: EpisodeRef[];
  /** Индекс текущей серии в [episodes]; −1 у фильма. */
  currentEpisode: number;
  // --- откуда это и что есть ещё ---
  /** Какой источник отдал ссылку: по нему видно, кто сейчас работает, а кто нет. */
  sourceId: string;
  sourceName: string;
  /**
   * Озвучки и качества, которые этот же источник даёт для этой же серии. Это ВАРИАНТЫ ССЫЛКИ —
   * в отличие от `voices`, которые лежат дорожками внутри одного файла (как у Collaps).
   */
  /**
   * Меню озвучек по всем источникам, в порядке предпочтения. `index` — постоянный номер варианта:
   * список дополняется, пока ищут остальные источники, и номер по месту в списке устарел бы.
   */
  choices: {
    voice: string;
    quality: string | null;
    source: string;
    index: number;
    /** Голос — дорожка внутри файла этого варианта (Collaps): выбрать её — открыть файл с ней. */
    track?: string;
  }[];
  choice: number;
  /** Дорожки внутри файла не показывать: этот вариант — одна озвучка (английский оригинал). */
  hideFileTracks?: boolean;
};

/**
 * ПЕРЕДАЧА ЗАПРОСА ПЛЕЕРУ — через модуль, а не через параметры маршрута.
 *
 * В параметрах ездят только строки, а здесь список серий, заголовки и десяток полей контекста.
 * Складывать это в адрес значит кодировать и раскодировать JSON на каждом открытии — и получить
 * экран, который нельзя открыть иначе как с уже готовым запросом. Плеер всегда открывается
 * изнутри приложения, поэтому запрос просто кладётся сюда, а маршрут остаётся коротким.
 */
let pending: PlaybackRequest | null = null;

export function setPendingPlayback(req: PlaybackRequest): void {
  pending = req;
}

export function takePendingPlayback(): PlaybackRequest | null {
  return pending;
}

/**
 * ЖИВА ЛИ ССЫЛКА.
 *
 * Срок годности написан в самом адресе параметром `t=` — обычная секундная метка. Берём запас в
 * пять минут: попасть в последнюю минуту срока значит получить обрыв на середине серии. Метку не
 * нашли — считаем живой: дальше за этим следит сам плеер.
 */
export function linkAlive(url: string): boolean {
  const m = /[?&]t=(\d{9,11})\b/.exec(url);
  if (!m) return true;
  const until = Number(m[1]) * 1000;
  if (!Number.isFinite(until)) return true;
  return Date.now() < until - 5 * 60_000;
}

/*
  ПАМЯТЬ НА ТО, ЧТО УЖЕ ИГРАЛО.

  Кэш видео хранится ПО АДРЕСУ ФАЙЛА, а адрес здесь подписанный и временный. Открыть то же самое
  другим адресом — значит для кэша открыть другой файл и честно скачать всё заново. Поэтому при
  повторном открытии подставляем ТОТ ЖЕ адрес, пока он не просрочен.

  И отдельно, из горького опыта: эта память работает и для серий тоже — но ТОЛЬКО потому, что
  теперь ссылка серии приходит из разобранной страницы, а не собирается запросом. Когда-то здесь
  оседала заставка про подписку, и каждое следующее открытие отдавало её мгновенно, вообще не
  обращаясь к источнику; три исправления подряд выглядели как «ничего не изменилось», потому что
  проверялась память, а не код. Если такое повторится — смотреть сюда ПЕРВЫМ делом.
*/
const recent = new Map<string, PlaybackRequest>();
const RECENT_LIMIT = 8;

export function rememberPlayback(req: PlaybackRequest): void {
  recent.delete(req.mediaKey);
  recent.set(req.mediaKey, req);
  if (recent.size > RECENT_LIMIT) {
    const oldest = recent.keys().next().value;
    if (oldest !== undefined) recent.delete(oldest);
  }
}

/** То же, что уже открывали. Null — не открывали или адрес просрочен. */
export function recallPlayback(mediaKey: string): PlaybackRequest | null {
  const kept = recent.get(mediaKey);
  if (!kept) return null;
  if (!linkAlive(kept.url)) {
    recent.delete(mediaKey);
    return null;
  }
  return kept;
}

/** Забыть запомненное: адрес оказался негодным, и повторять его незачем. */
export function forgetPlayback(mediaKey: string): void {
  recent.delete(mediaKey);
}

/** Забыть всё, что играло, — «Очистить историю». */
export function forgetAllPlayback(): void {
  recent.clear();
}
