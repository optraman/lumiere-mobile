import { memo } from 'react';
import { Animated, StyleSheet, View } from 'react-native';
import type { MediaItem } from '../types/media';
import { PosterCard } from './PosterCard';
import { colors } from '../theme/colors';
import { font } from '../theme/fonts';
import { usePortraitWindow } from '../nav/portrait';

const RANK_SIZE = 150;
/** Ширина коробки под цифру ФИКСИРОВАНА, хотя «1» уже «10». Без этого шаг ряда плавал бы от
 * элемента к элементу, и параллакс, который считается от номера позиции, разъезжался бы к концу. */
const RANK_BOX_W = 86;
const POSTER_W = 116;
/**
 * ОТРИЦАТЕЛЬНЫЙ отступ: цифра заезжает ПОД карточку («немножечко заходят за карточки»). Постер
 * рисуется после цифры, поэтому оказывается сверху — как в Cards.kt.
 *
 * Заход НЕГЛУБОКИЙ. Пробовал прятать цифру сильнее (−46), и она превращалась в неразборчивый
 * обрубок: у крупного кегля под постером оставалась половина глифа, а по цифре «10» и вовсе не
 * читалось, что это десятка. Четырнадцати точек хватает, чтобы номер и постер выглядели одним
 * предметом, а не двумя рядом стоящими, и при этом цифра остаётся целой.
 */
const OVERLAP = -14;
const GAP = 10;

/** Шаг ряда: на нём держится расчёт параллакса. */
export const TOP10_ITEM_W = RANK_BOX_W + OVERLAP + POSTER_W + GAP;

/**
 * Насколько цифра отстаёт от своего постера, в точках.
 *
 * Убавлено с 30 до 18: теперь, когда цифра почти не спрятана под постером, тот же сдвиг стал
 * заметнее и читался как самостоятельное движение, а не как глубина. Глубина тем и хороша, что
 * её замечаешь не сразу.
 */
const RANK_DRIFT = 18;

/** Отступ ряда от края экрана — тот же, что в contentContainerStyle списка. Нужен, чтобы знать,
 * где элемент оказывается на экране. */
const ROW_PAD = 16;

export const Top10Card = memo(function Top10Card({
  rank,
  item,
  index,
  total,
  scrollX,
}: {
  rank: number;
  item: MediaItem;
  index: number;
  /** Сколько всего цифр в ряду. Нужно, чтобы подсветка успела обойти все, включая крайние. */
  total: number;
  /** Прокрутка ряда. Без неё карточка работает как раньше, просто без параллакса. */
  scrollX?: Animated.Value;
}) {
  /**
   * ПАРАЛЛАКС ВНУТРИ ЭЛЕМЕНТА: цифра движется медленнее своего постера.
   *
   * Считается от положения ИМЕННО ЭТОГО элемента в ряду: пока он идёт к центру, цифра подтягивается
   * к постеру, пройдя центр — отстаёт. Поэтому эффект заметен на каждом элементе по отдельности, а
   * не выглядит как общий сдвиг всего ряда вбок.
   *
   * Сдвиг ограничен: цифра и так наполовину скрыта постером, и уехав дальше она вылезла бы из-под
   * него с другой стороны.
   */
  const { width: screenW } = usePortraitWindow();

  /**
   * СВЕЧЕНИЕ ИДЁТ ЗА ПОСТЕРОМ, А НЕ ЗА ЦИФРОЙ.
   *
   * Цифра — подпись к карточке, а не самостоятельный предмет: смотрят на постер, и загораться
   * должна цифра ТОГО постера, который сейчас в центре. Предыдущая версия делила весь ход
   * прокрутки поровну между цифрами и зажигала их по доле пройденного пути — свет шёл ровно, но
   * мимо: подсвеченной оказывалась цифра соседа, а не той карточки, на которую человек смотрит.
   *
   * Поэтому пик считается от положения САМОГО ПОСТЕРА: сдвиг ряда, при котором его середина
   * совпадает с серединой экрана. Свет гаснет к соседям на расстоянии одного шага ряда — ровно
   * там, где загорается следующий, поэтому переход остаётся перетеканием, а не перещёлкиванием.
   *
   * ЗАЖИМ ПО КРАЯМ — то, ради чего затевалась прежняя схема, и он сохранён. Ряд физически не может
   * прокрутиться так, чтобы первая или последняя карточка встала посередине: в начале единица
   * прижата к левому краю, в конце десятка — к правому. Их пики уезжают за пределы возможного
   * хода, поэтому подтягиваются к его границам, а сами цифры удерживают свет за краем (см.
   * outputRange). Иначе крайние две не подсветились бы никогда.
   */
  const contentW = total * TOP10_ITEM_W + ROW_PAD * 2;
  const maxScroll = Math.max(contentW - screenW, 0);
  /** Сдвиг ряда, при котором середина ЭТОГО постера совпадает с серединой экрана. */
  const centered =
    ROW_PAD + index * TOP10_ITEM_W + RANK_BOX_W + OVERLAP + POSTER_W / 2 - screenW / 2;
  const glowAt =
    maxScroll > 0 ? Math.min(Math.max(centered, 0), maxScroll) : centered;
  /** Расстояние до пика соседа — это и есть шаг ряда. */
  const step = TOP10_ITEM_W;

  const first = index === 0;
  const last = index === total - 1;

  const glow = scrollX
    ? scrollX.interpolate({
        inputRange: [glowAt - step, glowAt, glowAt + step],
        /**
         * КРАЙНИЕ ЦИФРЫ УДЕРЖИВАЮТ СВЕТ, и это не поблажка, а исправление.
         *
         * У первой пик приходится на нулевую прокрутку, у последней — на самый конец хода. Если
         * гасить их симметрично с обеих сторон, обе горят лишь в единственной точке: чуть
         * качнулся — и уже потухли. Поэтому первая светится ДО своего пика, а последняя — ПОСЛЕ
         * своего. Промежуточные гаснут в обе стороны, как и должны.
         */
        outputRange: [first ? 1 : 0, 1, last ? 1 : 0],
        extrapolate: 'clamp',
      })
    : first
      ? 1
      : 0;

  /**
   * Лёгкий рост карточки в фокусе — и ТОЛЬКО он.
   *
   * Внутреннего параллакса (когда картинка внутри росла сильнее рамки) здесь больше нет: на такой
   * маленькой карточке он читался не как глубина, а как рассогласование, и вместе с ростом рамки
   * выталкивал карточку за пределы ряда.
   *
   * Сам рост убавлен до двух процентов: соседние карточки стоят вплотную, и всё, что больше,
   * налезает на них и вылезает за край ряда.
   */
  const cardScale =
    typeof glow === 'number'
      ? 1 + 0.02 * glow
      : glow.interpolate({ inputRange: [0, 1], outputRange: [1, 1.02] });

  const drift = scrollX
    ? scrollX.interpolate({
        inputRange: [(index - 1) * TOP10_ITEM_W, index * TOP10_ITEM_W, (index + 1) * TOP10_ITEM_W],
        outputRange: [-RANK_DRIFT, 0, RANK_DRIFT],
        extrapolate: 'clamp',
      })
    : 0;

  return (
    <View style={styles.row}>
      <View style={styles.rankBox}>
        {/*
          ДВА СЛОЯ ОДНОЙ ЦИФРЫ: приглушённый снизу и светящийся сверху, у которого анимируется
          прозрачность.
          Так сделано потому, что ни цвет текста, ни радиус его свечения анимировать нельзя — эти
          свойства недоступны нативному драйверу, и любая попытка вела бы либо к рывкам, либо к той
          же ошибке смешения драйверов, на которую мы уже наступали с точками. Прозрачность
          нативному драйверу доступна, а наложение двух копий даёт ровно тот же результат.
        */}
        <Animated.Text
          style={[styles.rank, { transform: [{ translateX: drift }] }]}
          allowFontScaling={false}
          numberOfLines={1}
        >
          {rank}
        </Animated.Text>
        <Animated.Text
          style={[styles.rank, styles.rankGlow, { opacity: glow, transform: [{ translateX: drift }] }]}
          allowFontScaling={false}
          numberOfLines={1}
          pointerEvents="none"
        >
          {rank}
        </Animated.Text>
      </View>
      {/*
        ТОЧКА РОСТА ЗАВИСИТ ОТ ПОЛОЖЕНИЯ В РЯДУ.
        Карточка растёт от центра, то есть раздаётся в обе стороны, — и у первой карточки левая
        сторона уходит за край ряда, потому что слева у неё только отступ в 16 точек. Поэтому
        первая растёт ВПРАВО (точка роста у левого края), последняя — влево, остальные от центра.
        Так рост всегда направлен внутрь ряда.
      */}
      <Animated.View
        style={{
          transform: [{ scale: cardScale }],
          transformOrigin: first ? 'left center' : last ? 'right center' : 'center',
        }}
      >
        <PosterCard item={item} width={POSTER_W} style={{ marginLeft: OVERLAP }} />
      </Animated.View>
    </View>
  );
})

const styles = StyleSheet.create({
  row: { flexDirection: 'row', alignItems: 'center', marginRight: GAP },
  rankBox: {
    width: RANK_BOX_W,
    justifyContent: 'center',
    // Цифре разрешено выходить за коробку: иначе крупный кегль обрезался бы по её краям.
    overflow: 'visible',
    height: POSTER_W * 1.5,
  },
  // Цифра приглушённая, как RANK_FILL_DIM в оригинале (там вертикальный градиент #4A4A54 → #1B1B20;
  // в React Native градиент по тексту без доп. библиотеки не сделать, поэтому взят ровный тон).
  rank: {
    fontFamily: font.rank,
    fontSize: RANK_SIZE,
    lineHeight: RANK_SIZE * 1.1,
    /**
     * Отрицательный трекинг — ради «10»: гарнитура Array Bold Wide широкая по построению, и на
     * кегле 150 между единицей и нулём зияла дыра, из-за которой число читалось как две отдельные
     * цифры. Значение подобрано по этой паре — она единственная двузначная в десятке, на
     * однозначных трекинг ничего не меняет.
     */
    letterSpacing: -14,
    color: '#5C5C68',
  },
  /**
   * Светящаяся копия лежит ПОВЕРХ приглушённой, в тех же координатах.
   *
   * Цвет — пергаментный акцент приложения, а не белый: белое свечение на почти чёрном фоне читается
   * как засветка экрана, а тёплое — как подсветка предмета. Тень того же цвета с нулевым смещением
   * даёт ореол вокруг глифа.
   */
  rankGlow: {
    ...StyleSheet.absoluteFill,
    color: colors.focusFill,
    textShadowColor: 'rgba(204, 204, 153, 0.55)',
    textShadowOffset: { width: 0, height: 0 },
    // Радиус убавлен с 22: у первой цифры ореол такого размера вылезал за левый край ряда —
    // слева от неё всего 16 точек отступа, и свечение уходило за границу экрана.
    textShadowRadius: 13,
  },
});
