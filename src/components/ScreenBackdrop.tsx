import { Animated, StyleSheet, View } from 'react-native';

/**
 * Подложка под всплывающим экраном.
 *
 * ЗДЕСЬ БЫЛО ГАУССОВО РАЗМЫТИЕ, и его пришлось убрать — не из-за вкуса, а из-за цены.
 *
 * BlurView в iOS — это UIVisualEffectView: система пересчитывает размытие каждый кадр, пока
 * содержимое под ним меняется. У этого слоя ЕЩЁ И АНИМИРУЕТСЯ ПРОЗРАЧНОСТЬ, а под ним лежит экран
 * с непрерывно движущимся свечением. Полноэкранное размытие, пересобираемое каждый кадр поверх
 * анимированного фона, и с анимированной прозрачностью сверху — это самая дорогая вещь, какую
 * вообще можно нарисовать на телефоне. Именно она подъедала кадры в конце сворачивания: анимация
 * доезжала до последних процентов и «залипала», потому что рисующий поток не успевал.
 *
 * Размытие всё равно почти не видно: страница поверх непрозрачна и закрывает экран целиком,
 * подложка показывается только в те полторы десятых секунды, пока идёт разворот. Поэтому здесь
 * обычное затемнение с тем же тёплым налётом — на глаз в движении неотличимо, а стоит ноль.
 */
export function ScreenBackdrop({ style }: { style?: Animated.WithAnimatedObject<object> }) {
  return (
    <Animated.View style={[StyleSheet.absoluteFill, style]} pointerEvents="none">
      <View style={styles.dim} />
      <View style={styles.tint} />
    </Animated.View>
  );
}

const styles = StyleSheet.create({
  dim: { ...StyleSheet.absoluteFill, backgroundColor: 'rgba(8,8,10,0.62)' },
  tint: { ...StyleSheet.absoluteFill, backgroundColor: 'rgba(204, 204, 153, 0.05)' },
});
